#!/usr/bin/env bash
set -e

RULER_SOURCE="$HOME/.ruler"
TARGET_AGENTS_DIR=".agents"
TARGET_AGENTS_MD="AGENTS.md"

echo "[Ruler] Initializing local environment in: $(pwd)"

if [ ! -d "$RULER_SOURCE" ]; then
    echo "Error: $RULER_SOURCE directory not found. Please run installer first."
    exit 1
fi

mkdir -p "$TARGET_AGENTS_DIR"

for folder in docs rules skills packs; do
    if [ -d "$RULER_SOURCE/$folder" ]; then
        mkdir -p "$TARGET_AGENTS_DIR/$folder"
        cp -rn "$RULER_SOURCE/$folder/"* "$TARGET_AGENTS_DIR/$folder/" 2>/dev/null || true
    fi
done

echo "  ✓ Populated ./$TARGET_AGENTS_DIR from ~/.ruler/"

cat <<'EOF' > "$TARGET_AGENTS_MD"
# AGENT OPERATING GUIDELINES & RULES

> MANDATORY SYSTEM DIRECTIVE:
> Before executing any task or generating code, you MUST recursively read and strictly obey all instructions, styles, skills, and workflows stored inside the `./.agents/` directory and its subdirectories.

## Execution Requirements
1. Traverse and load every file in `./.agents/` before responding.
2. Follow all coding styles, conventions, and architecture guidelines specified in `./.agents/`.
3. Do not modify files outside task scope or alter existing layout structures unless directed.
EOF
echo "  ✓ Generated $TARGET_AGENTS_MD"

mkdir -p .cursor/rules
cat <<EOF > .cursor/rules/ruler.mdc
---
description: Master rules pointer generated by Agent Ruler
alwaysApply: true
---
Read AGENTS.md and recursively traverse all files inside .agents/ before executing any user prompt.
EOF

mkdir -p .opencode/agents
cat <<EOF > .opencode/agents/build.md
---
description: Primary agent instructions generated by Agent Ruler
mode: primary
---
Read AGENTS.md and recursively traverse all files inside .agents/ before executing any user prompt.
EOF

echo "✅ Done! Agent is fully aware of rules and ready to run."